    parser.add_argument("--skill-name", default="", help="Desired skill identifier")
    parser.add_argument("--output-dir", default=None, help="Output directory for generated skill")
    args = parser.parse_args()

    summary = forge(args.profile, args.skill_name, args.output_dir)

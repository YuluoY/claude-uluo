def _generate_domain_knowledge(skill_name: str, profile: dict) -> str:
    lines = [f"# {skill_name} — Domain Knowledge", ""]
    for exp in profile.get("expertise", []):
        lines.append(f"## {exp['domain']} ({exp['level']})")
        lines.append("")
        evidence = exp.get("evidence", [])
        if evidence:
            for e in evidence[:5]:
                lines.append(f"- {e}")
        lines.append("")
    return "\n".join(lines)


def _generate_communication_guide(skill_name: str, profile: dict) -> str:
    style = profile.get("style", {})
    lines = [
        f"# {skill_name} — Communication Guide",
        "",
        f"**Formality**: {style.get('formality', 5)}/10",
        f"**Explanation Style**: {style.get('explanation_style', 'balanced')}",
        "",
        "## Signature Phrases",
    ]
    for p in style.get("phrases", []):
        lines.append(f"- {p}")
    lines.append("")
    lines.append("## Sentence Patterns")
    for p in style.get("patterns", []):
        lines.append(f"- {p}")
    return "\n".join(lines)


def _generate_tool_preferences(skill_name: str, profile: dict) -> str:
    lines = [f"# {skill_name} — Tool Preferences", ""]
    for tool in profile.get("tools", []):
        lines.append(f"- **{tool['name']}**: {tool.get('usage', '')}")
    return "\n".join(lines)


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------

def _load_profile(path: str) -> Optional[dict]:
    p = Path(path)
    if not p.exists():
        raise FileNotFoundError(f"Profile not found: {path}")
    return json.loads(p.read_text(encoding="utf-8"))


def _derive_skill_name(profile: dict) -> str:
    """Derive a kebab-case skill name from persona info."""
    name = profile.get("persona_name", "unknown")
    name = name.lower().replace(" ", "-").replace("@", "").replace("/", "-")
    name = re.sub(r'[^a-z0-9-]', '', name)
    name = re.sub(r'-+', '-', name)  # Collapse multiple hyphens
    domains = [d["domain"].lower().replace(" ", "-") for d in profile.get("expertise", [])[:2]]
    if domains:
        name = f"{name}-{'-'.join(domains)}"
    return name[:50]


def _print_header(title: str):
    print(f"\n{'='*60}")
    print(f"  {title}")
    print(f"{'='*60}")


def _print_footer(output_dir: str, file_count: int):
    print(f"\n{'='*60}")
    print(f"  Skill written to: {output_dir}")
    print(f"  Files created: {file_count}")
    print(f"{'='*60}\n")



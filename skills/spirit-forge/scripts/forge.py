#!/usr/bin/env python3
"""
Spirit Forge — Phase 3: Forge (遣将)

Generate a working Claude Code SKILL.md from a persona-profile.json.
Reads the profile, applies skill-template.md, and produces a complete
skill directory with SKILL.md, references/, and supporting files.

Usage:
    python forge.py <persona-profile.json> [--skill-name <name>] [--output-dir <path>]
"""

import argparse
import json
import re
import sys
from datetime import datetime, timezone
from pathlib import Path
from typing import Optional

# Allow running from skill root or scripts/ directory
_skill_root = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(_skill_root))


# ---------------------------------------------------------------------------
# Main forge function
# ---------------------------------------------------------------------------

def forge(profile_path: str, skill_name: str = "", output_dir: Optional[str] = None) -> dict:
    """Generate a complete skill from a persona profile.

    Args:
        profile_path: Path to persona-profile.json
        skill_name: Desired skill identifier (auto-derived if empty)
        output_dir: Where to write the generated skill directory

    Returns:
        Summary dict with files created
    """
    profile = _load_profile(profile_path)
    if not profile:
        raise ValueError(f"Failed to load profile: {profile_path}")

    _print_header("Phase 3: Forge (遣将)")

    # Derive skill name
    if not skill_name:
        skill_name = _derive_skill_name(profile)
    print(f"  Skill name: {skill_name}")

    # Set up output directory
    if output_dir is None:
        output_dir = f".spirit-forge/{skill_name}/generated-skill"
    out = Path(output_dir)
    out.mkdir(parents=True, exist_ok=True)
    (out / "references").mkdir(parents=True, exist_ok=True)

    files_created = []

    # ---- Generate SKILL.md ----
    print("  Generating SKILL.md ...")
    skill_md = _generate_skill_md(skill_name, profile)
    (out / "SKILL.md").write_text(skill_md, encoding="utf-8")
    files_created.append("SKILL.md")

    # ---- Generate reference files ----
    print("  Generating references/ ...")

    domain_knowledge = _generate_domain_knowledge(skill_name, profile)
    (out / "references" / "domain-knowledge.md").write_text(domain_knowledge, encoding="utf-8")
    files_created.append("references/domain-knowledge.md")

    comm_guide = _generate_communication_guide(skill_name, profile)
    (out / "references" / "communication-guide.md").write_text(comm_guide, encoding="utf-8")
    files_created.append("references/communication-guide.md")

    if profile.get("tools"):
        tool_prefs = _generate_tool_preferences(skill_name, profile)
        (out / "references" / "tool-preferences.md").write_text(tool_prefs, encoding="utf-8")
        files_created.append("references/tool-preferences.md")

    # ---- Generate .claude-plugin/plugin.json ----
    (out / ".claude-plugin").mkdir(parents=True, exist_ok=True)
    plugin_json = {
        "name": skill_name,
        "version": "0.1.0",
        "description": profile.get("persona_name", skill_name) + " emulation skill — generated by Spirit Forge",
        "author": {"name": "claude-uluo (via Spirit Forge)"},
        "keywords": [d["domain"] for d in profile.get("expertise", [])[:5]],
        "license": "MIT",
        "skills": "./",
    }
    with open(out / ".claude-plugin" / "plugin.json", "w") as f:
        json.dump(plugin_json, f, ensure_ascii=False, indent=2)
    files_created.append(".claude-plugin/plugin.json")

    summary = {
        "skill_name": skill_name,
        "output_dir": str(out),
        "files_created": files_created,
    }
    _print_footer(str(out), len(files_created))
    return summary


